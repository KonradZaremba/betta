using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Betta.Lock;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using static Betta.Generators.BettaComponentGenerator;

namespace Betta.Generators
{
    /// <summary>
    /// <c>betta.lock</c>: the GUID of every component the plugin has published, one
    /// <c>guid Type.Method</c> line each, checked in next to the project. A locked GUID that no
    /// <c>[GrasshopperMethod]</c> answers to any more is a rename that breaks saved .gh files,
    /// reported as BETTA012 (the rules are in <see cref="GuidLockCore"/>, shared with Betta.Mcp).
    /// The generator only reads the file: it lists components not yet locked in
    /// <see cref="PendingHintName"/>, and the Betta.Generators build targets append them.
    /// </summary>
    internal static class GuidLock
    {
        internal const string PendingHintName = "BettaLockPending.g.cs";
        // Betta.Generators.targets matches this prefix.
        internal const string PendingPrefix = "// add: ";

        // Diagnostic properties Betta.Generators.CodeFixes reads: a LockFix name and its value.
        internal const string FixProperty = "BettaLockFix";
        internal const string ValueProperty = "BettaLockValue";

        internal static readonly DiagnosticDescriptor BETTA012_LockedComponentGone = new(
            id: "BETTA012",
            title: "A component in betta.lock no longer exists",
            messageFormat: GuidLockCore.MessageFormat,
            category: "Betta",
            defaultSeverity: DiagnosticSeverity.Warning,
            isEnabledByDefault: true);

        /// <summary>
        /// Reports BETTA012 for each locked GUID nothing answers to, on the method to fix when
        /// there's a likely one, else on the lock line, and emits the components to add to the
        /// lock. <paramref name="lockFile"/> is null before the first build writes it.
        /// </summary>
        internal static void Run(SourceProductionContext spc, IReadOnlyCollection<ServiceTypeModel> types, AdditionalText lockFile)
        {
            var text = lockFile?.GetText(spc.CancellationToken);
            var entries = text == null ? new List<LockEntry>() : GuidLockCore.Parse(text.Lines.Select(l => l.ToString()));
            var components = types
                .SelectMany(t => t.Methods.Select(m => new LockComponent(t.FullName, m.MethodName, m.Overloaded,
                    m.Parameters.Select(p => p.TypeFullName).ToArray(), m.Guid, m.FormerGuids, m.Enabled, m)))
                .ToList();
            var result = GuidLockCore.Check(entries, components);

            foreach (var finding in result.Gone)
            {
                var span = text.Lines[finding.Entry.Line].Span;
                var lockLine = Location.Create(lockFile.Path, span, text.Lines.GetLinePositionSpan(span));
                var at = (finding.Target?.Source as MethodModel)?.Location;
                if (at != null && !at.IsInSource) at = null;
                var properties = at == null || finding.Fix == LockFix.None
                    ? null
                    : ImmutableDictionary<string, string>.Empty
                        .Add(FixProperty, finding.Fix.ToString())
                        .Add(ValueProperty, finding.FixValue);
                spc.ReportDiagnostic(Diagnostic.Create(BETTA012_LockedComponentGone,
                    at ?? lockLine, at != null ? new[] { lockLine } : null, properties,
                    finding.Entry.Label, finding.Entry.Guid.ToString("D"), finding.Hint));
            }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/> Betta source generator.");
            sb.AppendLine("// The components this build adds to betta.lock, read by the Betta.Generators");
            sb.AppendLine("// build targets. Nothing in this file is compiled.");
            if (result.Gone.Count > 0)
                sb.AppendLine("// Nothing is added while betta.lock has components nothing answers to (BETTA012).");
            foreach (var component in result.ToAdd)
                sb.AppendLine(PendingPrefix + GuidLockCore.Line(component));
            spc.AddSource(PendingHintName, sb.ToString());
        }
    }
}
